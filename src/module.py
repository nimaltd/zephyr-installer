"""
The library as a Zephyr module: zephyr/module.yml, CMakeLists.txt and Kconfig.

Zephyr builds a module's code only when the module says how, in a folder called
zephyr inside it. A library written for any project has no such folder, so it
is written here, from installer.yml, into the folder the library was installed
in. It is written again on every install and update, so a source file the new
version adds is built without anyone editing anything.

A library that ships its own zephyr/module.yml knows its build better than
this does, and is left alone.

The module is named <library>_lib, not after the library itself. Zephyr keeps
one module per name, and a module added by the application quietly replaces a
module of the workspace with the same name: a library called littlefs would
otherwise take the place of Zephyr's own littlefs.
"""

import re
from pathlib import Path

from .core import usercode
from .core.files import backup
from .core.target import ALREADY, CHANGED, MANUAL, Outcome

NAME = "Zephyr module"

# The first line of each file written here, so a file of the library's own is
# never mistaken for one this wrote.
MARK = "# Generated by zephyr-installer"


def module_name(library):
    """The module's name: ee24_lib for ee24."""
    return re.sub(r"[^A-Za-z0-9_-]", "_", library.name) + "_lib"


def cmake_quote(text):
    """
    Text as one quoted CMake argument.

    A file name lands in CMakeLists.txt as it stands, so a quote, a dollar or a
    semicolon in it could otherwise end the argument, expand a variable or
    split it into two.
    """
    escaped = str(text).replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace(";", "\\;")

    return f'"{escaped}"'


def _in_module(relative):
    """A path inside the module, for its CMakeLists.txt."""
    if relative in (".", ""):
        return '"${ZEPHYR_CURRENT_MODULE_DIR}"'

    return '"${ZEPHYR_CURRENT_MODULE_DIR}/' + cmake_quote(relative)[1:]


def section(library):
    """The name of the USER CODE section in the module's CMakeLists.txt: EXAMPLE_CMAKE."""
    return f"{library.zephyr.symbol}_CMAKE"


def _label(library):
    return f"{library.name} {library.version}".strip()


def module_yml(library):
    """zephyr/module.yml, which tells Zephyr where the other two files are."""
    return f"""{MARK} for {_label(library)}. Written again on
# every install and update, so a change made here does not last.

name: {module_name(library)}
build:
  cmake: zephyr
  kconfig: zephyr/Kconfig
"""


def cmakelists(library):
    """zephyr/CMakeLists.txt: the library's files, built when its symbol is set."""
    symbol = library.zephyr.symbol
    lines = [
        f"{MARK} for {_label(library)}.",
        "#",
        "# Zephyr reads this because the application's CMakeLists.txt adds this folder",
        f"# to ZEPHYR_EXTRA_MODULES, and builds the library only when CONFIG_{symbol} is",
        "# set, which prj.conf does. Written again on every install and update, so a",
        "# change made here does not last. The files come from the library's",
        "# installer.yml.",
        "",
        f"if(CONFIG_{symbol})",
    ]

    # On the include path of the whole build, the application's code too,
    # which is what includes the library's header.
    lines.append("  zephyr_include_directories(")
    lines.extend(f"    {_in_module(folder)}" for folder in library.include_dirs)
    lines.append("  )")

    # A library of headers only has nothing to compile, and Zephyr warns about
    # a library with no sources.
    if library.build_sources:
        lines.append("")
        lines.append(f"  zephyr_library_named({module_name(library)})")
        lines.append("  zephyr_library_sources(")
        lines.extend(f"    {_in_module(name)}" for name in library.build_sources)
        lines.append("  )")

    # For the whole build, not only the library's own files: a define can
    # change what the library's header declares, and every file including it
    # has to agree.
    if library.defines:
        lines.append("")
        lines.append("  zephyr_compile_definitions(")
        lines.extend(f"    {define}" for define in library.defines)
        lines.append("  )")

    if library.zephyr.cmake:
        lines.append("")
        lines.append(f"  # From {library.name}'s installer.yml.")
        lines.extend(f"  {line}" for line in library.zephyr.cmake)

    # The user's own lines, which every install carries over. Empty to start
    # with, so anything in it on an uninstall is the user's. A library of
    # headers only has no library of its own to give settings to.
    example = "zephyr_library_compile_definitions()" if library.build_sources else "zephyr_compile_definitions()"
    lines += [
        "",
        f"  # Lines of your own for {library.name}, such as",
        f"  # {example}, go between these two, and every",
        "  # install keeps them.",
        f"  # USER CODE BEGIN {section(library)}",
        f"  # USER CODE END {section(library)}",
        "endif()",
    ]

    return "\n".join(lines) + "\n"


def _help(lines):
    """A Kconfig help block, each line indented under it."""
    out = ["\thelp"]
    out.extend(f"\t  {line}" if line.strip() else "" for line in lines)

    return out


def kconfig(library):
    """zephyr/Kconfig: the library's switch, and its settings under it."""
    part = library.zephyr
    prompt = library.name + (f": {library.description}" if library.description else "")
    about = [line for line in (library.description, library.repository) if line]
    keyword = "menuconfig" if part.settings else "config"

    lines = [
        f"{MARK} for {_label(library)}. Written again on",
        "# every install and update, so a change made here does not last.",
        "",
        f"{keyword} {part.symbol}",
        f'\tbool "{one_line(prompt)}"',
    ]

    if about:
        lines.extend(_help(about))

    if part.settings:
        lines.append("")
        lines.append(f"if {part.symbol}")

        for setting in part.settings:
            lines.append("")
            lines.append(f"config {setting.name}")
            lines.append(f'\t{setting.type} "{setting.prompt}"')
            lines.append(f"\tdefault {setting.default}")

            if setting.range:
                lines.append(f"\trange {setting.format(setting.range[0])} {setting.format(setting.range[1])}")

            if setting.help:
                lines.extend(_help(setting.help))

        lines.append("")
        lines.append(f"endif # {part.symbol}")

    return "\n".join(lines) + "\n"


def one_line(text):
    """Text for a Kconfig prompt: one line, its quotes and backslashes escaped."""
    flat = " ".join(str(text).split())

    return flat.replace("\\", "\\\\").replace('"', '\\"')


def ships_its_own(destination):
    """Whether the library brought a zephyr/module.yml of its own."""
    path = Path(destination) / "zephyr" / "module.yml"

    try:
        return path.is_file() and not path.read_text(encoding="utf-8").startswith(MARK)
    except OSError:
        return True


def write(library, destination):
    """Write the three files, each only when it changed. Returns an Outcome."""
    folder = Path(destination) / "zephyr"

    if ships_its_own(destination):
        return Outcome(NAME, ALREADY, f"{library.name} has its own zephyr/module.yml, used as it is.")

    wanted = {
        "module.yml": module_yml(library),
        "CMakeLists.txt": cmakelists(library),
        "Kconfig": kconfig(library),
    }
    written = []
    steps = []
    saved = None

    try:
        folder.mkdir(parents=True, exist_ok=True)

        for name, text in wanted.items():
            path = folder / name
            data = text.encode("utf-8")
            old = path.read_bytes() if path.is_file() else None

            # What the user wrote between the USER CODE lines of the last copy
            # goes into the new one. Markers that no longer pair leave nothing
            # to carry, so the copy is put aside first, whole.
            if old is not None and name == "CMakeLists.txt":
                merged = usercode.merge(data, old)

                if merged.broken or merged.lost:
                    saved = backup(path)
                    steps.append(f"Your lines in zephyr/{name} could not be carried over: they are in {saved.name}.")
                else:
                    data = merged.data

                if merged.kept:
                    steps.append(f"Kept your USER CODE {', '.join(merged.kept)} in zephyr/{name}.")

            # Left alone when nothing changed, so the build does not see a
            # newer file and configure again for nothing.
            if old == data:
                continue

            path.write_bytes(data)
            written.append(name)
    except OSError as error:
        return Outcome(NAME, MANUAL, f"Could not write {folder}: {error}")

    if not written:
        return Outcome(NAME, ALREADY, f"{module_name(library)} is up to date.", steps)

    return Outcome(NAME, CHANGED, f"Wrote {module_name(library)}: zephyr/{', zephyr/'.join(written)}.",
                   steps, saved)


def _holds_yours(path):
    """Whether a CMakeLists.txt write() made has anything between its USER CODE lines."""
    try:
        lines, sections = usercode.parse(path.read_bytes())
    except usercode.MarkerError:
        return True

    return any(b"".join(lines[first:last]).strip() for first, last in sections.values())


def remove(destination):
    """
    Delete the three files write() made, and the zephyr folder when they were
    all it held. A library's own module is not touched.

    Returns the copy put aside of a CMakeLists.txt that had the user's lines
    in it, or None.
    """
    folder = Path(destination) / "zephyr"
    saved = None

    for name in ("module.yml", "CMakeLists.txt", "Kconfig"):
        path = folder / name

        try:
            if not (path.is_file() and path.read_text(encoding="utf-8").startswith(MARK)):
                continue

            if name == "CMakeLists.txt" and _holds_yours(path):
                saved = backup(path)

            path.unlink()
        except (OSError, UnicodeDecodeError):
            continue

    try:
        folder.rmdir()
    except OSError:
        pass

    return saved


# A symbol the Kconfig defines: config NAME, or menuconfig NAME.
_DEFINED = re.compile(r"^(?:menu)?config[ \t]+([A-Za-z0-9_]+)", re.MULTILINE)


def symbols(destination):
    """Every symbol the Kconfig write() made defines, read before it is removed."""
    path = Path(destination) / "zephyr" / "Kconfig"

    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return []

    return _DEFINED.findall(text) if text.startswith(MARK) else []
